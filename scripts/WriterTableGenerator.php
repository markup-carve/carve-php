<?php

declare(strict_types=1);

/**
 * Turns the data files the writer reads (`escape-contexts.json`) into the constants of
 * src/Generated/WriterTables.php.
 */
final class WriterTableGenerator
{
    /**
     * @param string $dir
     *
     * @return string
     */
    public static function generate(string $dir): string
    {
        $load = static function (string $name) use ($dir): array {
            $data = json_decode((string)file_get_contents($dir . '/' . $name . '.json'), true, 512, JSON_THROW_ON_ERROR);
            assert(is_array($data));

            return $data;
        };
        $triggers = [];
        $contexts = [];
        $escape = $load('escape-contexts');
        foreach ($escape['contexts'] as $context) {
            $contexts[$context['name']] = $context['triggers'];
            foreach ($context['triggers'] as $trigger) {
                $triggers[$trigger[0]] = true;
            }
        }
        ksort($triggers, SORT_STRING);
        $quiet = [];
        foreach ($escape['no_escape'] as $row) {
            $quiet[$row['name']] = $row['triggers'];
        }
        $consts = [
            'ESCAPE_CONTEXTS' => ['C2-W-088 to C2-W-099 escape-contexts.json: context => triggers', $contexts],
            'ESCAPE_TRIGGERS' => ['C2-W-089 escape-contexts.json: every first character of a trigger', implode('', array_keys($triggers))],
            'NO_ESCAPE' => ['C2-W-099 escape-contexts.json no_escape', $quiet],
        ];
        $out = "<?php\n\ndeclare(strict_types=1);\n\nnamespace MarkupCarve\\Carve\\Generated;\n\n";
        $out .= "/**\n * Generated by scripts/generate-tables.php from spec/data. Do not edit.\n */\nfinal class WriterTables\n{\n";
        foreach ($consts as $name => [$doc, $value]) {
            $out .= "    /** {$doc} */\n    public const {$name} = " . self::export($value, 1) . ";\n\n";
        }

        return rtrim($out) . "\n}\n";
    }

    private static function export(mixed $value, int $depth): string
    {
        if (!is_array($value)) {
            return var_export($value, true);
        }
        if ($value === []) {
            return '[]';
        }
        $pad = str_repeat('    ', $depth + 1);
        $list = array_is_list($value);
        $out = "[\n";
        foreach ($value as $k => $v) {
            $out .= $pad . ($list ? '' : var_export((string)$k, true) . ' => ') . self::export($v, $depth + 1) . ",\n";
        }

        return $out . str_repeat('    ', $depth) . ']';
    }
}
