<?php

declare(strict_types=1);

/**
 * Turns data/import-html.json into src/Generated/ImportTables.php, the tables of the HTML importer (import-html.md).
 */
final class ImportTableGenerator
{
    public static function generate(string $dir): string
    {
        $data = json_decode((string)file_get_contents($dir . '/import-html.json'), true, 512, JSON_THROW_ON_ERROR);
        assert(is_array($data));
        $elements = [];
        foreach ($data['elements'] as $row) {
            $elements[$row['name']] = $row['treatment'];
        }
        $attributes = [];
        foreach ($data['attributes'] as $row) {
            $attributes[$row['name']] = [$row['match'], $row['treatment']];
        }
        $codes = [];
        foreach ($data['codes'] as $row) {
            $codes[$row['id']] = $row['severity'];
        }
        $carriers = [];
        foreach ($data['losses'] as $row) {
            $carriers[$row['name']] = true;
        }
        $consts = [
            'ELEMENTS' => ['C2-M-056 C2-M-057 the table "Elements": name to treatment', $elements],
            'ATTRIBUTES' => ['C2-M-052 the table "Attributes": name to match and treatment', $attributes],
            'CODES' => ['C2-M-083 the codes of the importer and their severity', $codes],
            'CARRIERS' => ['C2-H-115 the 18 reserved names (the rows of `losses`)', $carriers],
        ];
        $out = "<?php\n\ndeclare(strict_types=1);\n\nnamespace MarkupCarve\\Carve\\Generated;\n\n";
        $out .= "/**\n * Generated by scripts/generate-tables.php from spec/data/import-html.json. Do not edit.\n */\n";
        $out .= "final class ImportTables\n{\n";
        foreach ($consts as $name => [$doc, $value]) {
            $out .= "    /** {$doc} */\n    public const " . $name . ' = ' . self::export($value) . ";\n\n";
        }

        return rtrim($out) . "\n}\n";
    }

    private static function export(array $value): string
    {
        $out = "[\n";
        foreach ($value as $key => $item) {
            $text = is_array($item) ? '[' . implode(', ', array_map(static fn (string $s): string => var_export($s, true), $item)) . ']'
                : var_export($item, true);
            $out .= '        ' . var_export((string)$key, true) . ' => ' . $text . ",\n";
        }

        return $out . '    ]';
    }
}
